/**
 * Função executada para realizar a carga de todos os 174 plantões e ~460 guarnições.
 * Pode ser executada diretamente pelo editor do Apps Script, pelo menu da planilha ou pela URL.
 */
function executarCargaHistoricaWhatsApp() {
  const ss = obterPlanilha_();
  const sheetPlantao = obterOuCriarAba_(ss, ABA_PLANTAO, [
    'ID_Turno', 'Data_Servico', 'Hora_Assuncao', 'Fracao', 'Posto_Equipe', 'Regime',
    'VTR_Placa', 'VTR_Prefixo', 'KM_Inicial', 'Material_Carga', 'Obs_Assuncao',
    'CMT_ou_Titular', 'Motorista', 'Patrulheiro', 'Despachante', 'Telefone_Funcional',
    'KM_Final', 'KM_Rodado', 'Abordagens_Pessoas', 'Abordagens_Veiculos',
    'Autos_Infracao', 'Remocoes_Veiculos', 'Status_Turno', 'Carimbo_Registro'
  ]);

  const sheetGuarnicao = obterOuCriarAba_(ss, ABA_GUARNICAO, [
    'ID_Turno', 'Data_Servico', 'Fracao', 'VTR_Placa', 'Policial', 'Funcao', 'Pontua_Equipe_VTR'
  ]);

  // Carrega efetivo oficial da aba 'todo_efetivo'
  const efetivoOficial = carregarEfetivoNormalizacao_(ss);

  // Lê plantões já existentes na planilha para evitar qualquer duplicidade
  const plantoesExistentes = new Set();
  if (sheetPlantao.getLastRow() > 1) {
    const valoresPlantao = sheetPlantao.getRange(2, 1, sheetPlantao.getLastRow() - 1, 4).getValues();
    valoresPlantao.forEach(linha => {
      const dataBr = formatarDataCelula_(linha[1]);
      const fracao = String(linha[3] || '').trim();
      if (dataBr && fracao) {
        plantoesExistentes.add(dataBr + '|' + fracao);
      }
    });
  }

  const linhasNovasPlantao = [];
  const linhasNovasGuarnicao = [];

  DADOS_HISTORICO_WHATSAPP.forEach(rec => {
    const chave = rec.data + '|' + rec.fracao;
    if (plantoesExistentes.has(chave)) {
      return; // Já cadastrado na planilha, ignora
    }

    // Normaliza nomes da equipe contra o todo_efetivo
    const cmtNorm = normalizarNomeComEfetivo_(rec.cmt, efetivoOficial);
    const motNorm = normalizarNomeComEfetivo_(rec.motorista, efetivoOficial);
    const patrNorm = normalizarNomeComEfetivo_(rec.patrulheiro, efetivoOficial);
    const despNorm = normalizarNomeComEfetivo_(rec.despachante, efetivoOficial);

    // Gera ID único do Turno
    const partesData = rec.data.split('/');
    const dataLimpa = partesData[2] + partesData[1] + partesData[0];
    const siglaFracao = rec.fracao.split('/')[0].replace(/[^A-Za-z0-9]/g, '').toUpperCase();
    const idTurno = dataLimpa + '-' + siglaFracao + '-RP01-WHATSAPP';

    linhasNovasPlantao.push([
      idTurno,
      rec.data,
      rec.hora || '08:00',
      rec.fracao,
      rec.posto || 'RP 01',
      rec.regime || '24h',
      rec.vtrPlaca || '',
      rec.vtrPrefixo || '',
      rec.kmInicial || 0,
      rec.materialCarga || 'S/A',
      rec.obs || 'Histórico importado do WhatsApp',
      cmtNorm,
      motNorm,
      patrNorm,
      despNorm,
      rec.telefone || '',
      '', 0, 0, 0, 0, 0,
      'Encerrado',
      'Carga Histórica WhatsApp'
    ]);

    // Guarnição
    const equipe = [
      { nome: cmtNorm, funcao: 'Comandante', pontua: 'Sim' },
      { nome: motNorm, funcao: 'Motorista', pontua: 'Sim' },
      { nome: patrNorm, funcao: 'Patrulheiro', pontua: 'Sim' },
      { nome: despNorm, funcao: 'Despachante', pontua: 'Não' }
    ];

    equipe.forEach(m => {
      if (m.nome && m.nome.trim() !== '') {
        linhasNovasGuarnicao.push([
          idTurno,
          rec.data,
          rec.fracao,
          rec.vtrPlaca || '',
          m.nome.trim(),
          m.funcao,
          m.pontua
        ]);
      }
    });

    plantoesExistentes.add(chave);
  });

  if (linhasNovasPlantao.length > 0) {
    sheetPlantao
      .getRange(sheetPlantao.getLastRow() + 1, 1, linhasNovasPlantao.length, 24)
      .setValues(linhasNovasPlantao);
  }

  if (linhasNovasGuarnicao.length > 0) {
    sheetGuarnicao
      .getRange(sheetGuarnicao.getLastRow() + 1, 1, linhasNovasGuarnicao.length, 7)
      .setValues(linhasNovasGuarnicao);
  }

  Logger.log('Carga concluída. Plantões: ' + linhasNovasPlantao.length + ' | Guarnições: ' + linhasNovasGuarnicao.length);

  return {
    sucesso: true,
    plantoesImportados: linhasNovasPlantao.length,
    registrosGuarnicao: linhasNovasGuarnicao.length
  };
}

function carregarEfetivoNormalizacao_(ss) {
  const sheet = ss.getSheetByName(ABA_EFETIVO);
  if (!sheet || sheet.getLastRow() < 2) return [];
  const dados = sheet.getDataRange().getValues();
  const lista = [];

  for (let i = 1; i < dados.length; i++) {
    const grad = String(dados[i][2] || '').trim();
    const nomeGuerra = String(dados[i][4] || '').trim();
    if (!nomeGuerra) continue;
    const gradCurta = grad ? grad.split(' ')[0] : '';
    const exibicao = (gradCurta ? gradCurta + ' ' : '') + nomeGuerra;

    lista.push({
      exibicao: exibicao,
      nomeGuerra: nomeGuerra.toUpperCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    });
  }
  // Nomes maiores primeiro
  lista.sort((a, b) => b.nomeGuerra.length - a.nomeGuerra.length);
  return lista;
}

function normalizarNomeComEfetivo_(nomeBruto, listaEfetivo) {
  if (!nomeBruto || typeof nomeBruto !== 'string') return '';
  const limpo = nomeBruto.trim();
  if (limpo.length < 3) return '';

  const semAcento = limpo.toUpperCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

  for (let i = 0; i < listaEfetivo.length; i++) {
    const ef = listaEfetivo[i];
    const regex = new RegExp('(?:^|[^A-Z])' + ef.nomeGuerra + '(?:$|[^A-Z])');
    if (regex.test(semAcento)) {
      return ef.exibicao;
    }
  }

  return limpo;
}
